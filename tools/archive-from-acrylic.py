# Copy the Material Identity Archive (the acrylic plate content) into the site.
# Usage: python3 tools/archive-from-acrylic.py /mnt/project-files/iam-acrylic/build/content_v03.py
# Writes js/data/archive.js. Re-run whenever the plate content changes, so online and offline match.
import json, os, runpy, sys
src = sys.argv[1]
c = runpy.run_path(src)
out = {}
for s in c["SUBJECTS"]:
    out[s["slug"]] = {k: s[k] for k in ("no", "name", "latin", "identity", "motto", "assignment", "agency", "statement", "on_record", "credit") if k in s}
# 9 Nov 2026 Lynn: the "on record" lines were all said by workshop participants, not by her.
CREDIT = {"I.A.M. · Lynn Zhong": "Workshop participant", "Lynn Zhong, Olivia, Rena": "Olivia, Rena"}
for v in out.values():
    if v.get("credit") in CREDIT: v["credit"] = CREDIT[v["credit"]]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
with open(f"{root}/js/data/archive.js", "w") as f:
    f.write(f"// MATERIAL IDENTITY ARCHIVE, the same content as the acrylic plates ({os.path.basename(src)}).\n")
    f.write("// Generated by tools/archive-from-acrylic.py. Do not edit here: edit the plate content and re-run.\n")
    f.write(f"export const ARCHIVE_TITLE = {json.dumps(c['TITLE'])};\nexport const ARCHIVE_SUBTITLE = {json.dumps(c['SUBTITLE'])};\n")
    f.write("export const ARCHIVE = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n")
print(len(out), "subjects")
